<#
.SYNOPSIS
    Bootstraps the TXA system on GitHub with the gh CLI.

.DESCRIPTION
    Publishes this folder as <Owner>/txa-repo and configures it:
      * merge settings (squash only, auto-merge allowed, delete merged branches)
      * workflow token = read-only, and it can never approve pull requests
      * TXA labels
      * CODEOWNERS generated from -Moderators / -Admins (or org teams)
      * branch protection on main: required status txa/verified, 1 approving review,
        code-owner review required, stale approvals dismissed, linear history
      * GitHub Pages (workflow build) for the txa.v1 API
      * repository variables used by the workflows

    Safe to re-run: every step is idempotent.

.EXAMPLE
    ./scripts/setup-github.ps1 -Owner TXAVL -Moderators alice,bob -Admins carol -ClientId Ov23liAbc123

.EXAMPLE
    # Organisation with teams instead of individual users
    ./scripts/setup-github.ps1 -Owner TXAVL -UseTeams
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string]$Owner,
    [string[]]$Moderators = @(),
    [string[]]$Admins = @(),
    [switch]$UseTeams,
    [string]$ManifestRepo = 'txa-repo',
    [ValidateSet('public', 'private')] [string]$Visibility = 'public',
    [string]$ClientId = '',
    [switch]$SkipPush
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$Manifest = "$Owner/$ManifestRepo"

function Write-Step([string]$Message) { Write-Host "`n== $Message" -ForegroundColor Cyan }

function Invoke-Gh {
    param([Parameter(ValueFromRemainingArguments)] [string[]]$Arguments)
    $output = & gh @Arguments
    if ($LASTEXITCODE -ne 0) { throw "gh $($Arguments -join ' ') failed (exit $LASTEXITCODE)" }
    return $output
}

function Invoke-GhSoft {
    param([Parameter(ValueFromRemainingArguments)] [string[]]$Arguments)
    # Windows PowerShell 5.1 turns native stderr into terminating errors under 'Stop',
    # even when redirected - relax it for calls that are allowed to fail.
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $output = & gh @Arguments 2>$null
        $ok = ($LASTEXITCODE -eq 0)
    } finally {
        $ErrorActionPreference = $previous
    }
    return [pscustomobject]@{ Ok = $ok; Output = $output }
}

function Publish-Folder([string]$Folder, [string]$Slug, [string]$Description) {
    $exists = (Invoke-GhSoft repo view $Slug --json name).Ok
    if (-not $exists) {
        Invoke-Gh repo create $Slug "--$Visibility" --description $Description | Out-Null
        Write-Host "   created $Slug"
    } else {
        Write-Host "   $Slug already exists"
    }
    if ($SkipPush) { return }
    Push-Location $Folder
    try {
        if (-not (Test-Path .git)) {
            git init -b main | Out-Null
            git remote add origin "https://github.com/$Slug.git"
        }
        git add -A
        git diff --cached --quiet
        if ($LASTEXITCODE -ne 0) { git commit -m "TXA bootstrap" | Out-Null }
        git push -u origin main
        if ($LASTEXITCODE -ne 0) { throw "git push to $Slug failed" }
    } finally {
        Pop-Location
    }
}

# ---------------------------------------------------------------------------- preflight
Write-Step 'Checking gh authentication'
Invoke-Gh auth status | Out-Null
$viewer = Invoke-Gh api user --jq .login
$ownerType = Invoke-Gh api "users/$Owner" --jq .type
Write-Host "   signed in as $viewer; owner '$Owner' is a $ownerType"
if ($UseTeams -and $ownerType -ne 'Organization') { throw '-UseTeams needs an organization owner' }
if (-not $UseTeams -and $Moderators.Count -eq 0) {
    $Moderators = @($viewer)
    Write-Host "   no -Moderators given - using $viewer (add volunteers later and re-run)" -ForegroundColor Yellow
}
if (-not $UseTeams -and $Admins.Count -eq 0) { $Admins = @($viewer) }

# ---------------------------------------------------------------------------- CODEOWNERS
Write-Step 'Generating CODEOWNERS'
if ($UseTeams) {
    foreach ($team in 'txa-moderators', 'txa-admins') {
        if (-not (Invoke-GhSoft api "orgs/$Owner/teams/$team").Ok) {
            Invoke-Gh api -X POST "orgs/$Owner/teams" -f "name=$team" -f privacy=closed | Out-Null
            Write-Host "   created team @$Owner/$team"
        }
    }
    $mods = "@$Owner/txa-moderators"
    $adms = "@$Owner/txa-admins"
} else {
    $mods = ($Moderators | ForEach-Object { "@$($_.TrimStart('@'))" }) -join ' '
    $adms = ($Admins | ForEach-Object { "@$($_.TrimStart('@'))" }) -join ' '
}
$codeowners = @"
# TXA code owners - generated by scripts/setup-github.ps1. The last matching pattern wins.
# Branch protection requires >= 1 approving review from a code owner (STEP 16 lock).
*                    $mods
/manifests/          $mods
/.github/            $adms
/policy.txa.yaml     $adms
/.gitattributes      $adms
/tools/              $adms
/scripts/            $adms
/examples/           $adms
/install.ps1         $adms
"@
[IO.File]::WriteAllText((Join-Path $Root '.github/CODEOWNERS'), ($codeowners -replace "`r`n", "`n") + "`n")
Write-Host "   moderators: $mods"
Write-Host "   admins:     $adms"

# ---------------------------------------------------------------------------- default slugs
if ($Manifest -ne 'TXAVL/txa-repo') {
    Write-Step "Pointing built-in defaults at $Manifest"
    $files = Get-ChildItem -Path $Root -Recurse -File -Include *.ps1, *.py, *.yml, *.md, *.toml |
        Where-Object { $_.FullName -notmatch '[\\/](\.venv|\.git|build|dist)[\\/]' -and $_.FullName -ne $PSCommandPath }
    foreach ($file in $files) {
        $text = [IO.File]::ReadAllText($file.FullName)
        $new = $text.Replace('TXAVL/txa-repo', $Manifest)
        if ($new -ne $text) {
            [IO.File]::WriteAllText($file.FullName, $new)  # UTF-8 without BOM
            Write-Host "   $($file.FullName.Substring($Root.Length + 1))"
        }
    }
}

# ---------------------------------------------------------------------------- repositories
Write-Step "Publishing $Manifest"
Publish-Folder $Root $Manifest 'TXA package manifests + txapm / txacreate tools'

# ---------------------------------------------------------------------------- settings
Write-Step 'Merge settings: squash only, auto-merge on, delete merged branches'
Invoke-Gh api -X PATCH "repos/$Manifest" `
    -F allow_auto_merge=true -F allow_squash_merge=true -F allow_merge_commit=false `
    -F allow_rebase_merge=false -F delete_branch_on_merge=true `
    -f squash_merge_commit_title=PR_TITLE -f squash_merge_commit_message=PR_BODY | Out-Null

Write-Step 'Workflow token: read-only and never allowed to approve PRs'
Invoke-Gh api -X PUT "repos/$Manifest/actions/permissions/workflow" `
    -f default_workflow_permissions=read -F can_approve_pull_request_reviews=false | Out-Null

Write-Step 'Labels'
$labels = @(
    @('txa:new-app', '1d76db', 'First release of a package that is not in txa-repo yet'),
    @('txa:new-version', '0e8a16', 'New version of an existing package'),
    @('txa:manifest-update', 'c5def5', 'Edits an already published version'),
    @('txa:removal', 'b60205', 'Removes a published version'),
    @('txa:validating', 'bfd4f2', 'The TXA bot is running its checks right now'),
    @('txa:verified-build', '2ea44f', 'All automated TXA checks passed'),
    @('txa:fix-required', 'd93f0b', 'At least one automated TXA check failed'),
    @('txa:needs-agreement', 'b60205', 'The contributor has not accepted the Contributor Agreement yet'),
    @('txa:needs-confirmation', 'e99695', 'The pull request checklist is not fully ticked yet'),
    @('txa:awaiting-review', 'fbca04', 'Waiting for a TXA moderator to approve'),
    @('txa:approved', '0e8a16', 'A code owner approved - merges as soon as the checks are green'),
    @('txa:published', '6f42c1', 'Merged - available through txapm after the index refresh'),
    @('txa:infra-change', '5319e7', 'Touches files outside manifests/ - admin review only')
)
foreach ($label in $labels) {
    Invoke-Gh label create $label[0] --repo $Manifest --color $label[1] --description $label[2] --force | Out-Null
    Write-Host "   $($label[0])"
}

Write-Step 'Repository variables'
if ($ClientId) {
    Invoke-Gh variable set TXA_GITHUB_CLIENT_ID --repo $Manifest --body $ClientId | Out-Null
    Write-Host "   TXA_GITHUB_CLIENT_ID=$ClientId (baked into txacreate.exe at release time)"
} else {
    Write-Host '   no -ClientId yet - see step 1 below'
}

Write-Step 'Moderator and admin access'
if ($UseTeams) {
    Invoke-Gh api -X PUT "orgs/$Owner/teams/txa-moderators/repos/$Manifest" -f permission=push | Out-Null
    Invoke-Gh api -X PUT "orgs/$Owner/teams/txa-admins/repos/$Manifest" -f permission=maintain | Out-Null
    Write-Host '   team permissions granted - add members with: gh api -X PUT orgs/<org>/teams/txa-moderators/memberships/<user>'
} else {
    $grants = @{}
    foreach ($user in $Moderators) { $grants[$user.TrimStart('@')] = 'push' }
    foreach ($user in $Admins) { $grants[$user.TrimStart('@')] = 'maintain' }
    foreach ($user in $grants.Keys) {
        if ($user -ieq $Owner -or $user -ieq $viewer) { continue }
        Invoke-Gh api -X PUT "repos/$Manifest/collaborators/$user" -f "permission=$($grants[$user])" | Out-Null
        Write-Host "   invited $user ($($grants[$user]))"
    }
}

Write-Step 'GitHub Pages (txa.v1 API)'
$pages = Invoke-GhSoft api -X POST "repos/$Manifest/pages" -f build_type=workflow
if ($pages.Ok) { Write-Host '   Pages enabled' } else { Write-Host '   Pages already enabled (or not available on this plan)' }

Write-Step 'Branch protection on main (Code Owner Review Lock)'
$protection = @'
{
  "required_status_checks": { "strict": false, "contexts": ["txa/verified"] },
  "enforce_admins": false,
  "required_pull_request_reviews": {
    "dismiss_stale_reviews": true,
    "require_code_owner_reviews": true,
    "required_approving_review_count": 1,
    "require_last_push_approval": true
  },
  "restrictions": null,
  "required_linear_history": true,
  "allow_force_pushes": false,
  "allow_deletions": false,
  "required_conversation_resolution": true
}
'@
# Windows PowerShell 5.1 re-encodes text piped into native programs, so hand gh a file.
$protectionFile = Join-Path ([IO.Path]::GetTempPath()) 'txa-protection.json'
[IO.File]::WriteAllText($protectionFile, $protection)
try {
    gh api -X PUT "repos/$Manifest/branches/main/protection" --input $protectionFile | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'branch protection failed (private repos need GitHub Pro/Team)' }
} finally {
    Remove-Item -LiteralPath $protectionFile -ErrorAction SilentlyContinue
}
Write-Host '   required: status txa/verified + 1 code-owner approval; squash auto-merge waits for both'

# ---------------------------------------------------------------------------- next steps
Write-Step 'Done. Remaining manual steps'
Write-Host @"
  1. Device Code Flow for the browser sign-in txacreate shows at the fork step:
       GitHub > Settings > Developer settings > OAuth Apps > New OAuth App
       tick 'Enable Device Flow', copy the Client ID, then:
       gh variable set TXA_GITHUB_CLIENT_ID --repo $Manifest --body <client-id>

  2. (Recommended) bot token so auto-merged PRs immediately refresh the API:
       fine-grained PAT on $Manifest with Contents + Pull requests: read/write
       gh secret set TXA_BOT_TOKEN --repo $Manifest

  3. Release the tools (builds txapm.exe / txacreate.exe):
       git tag v1.0.0; git push origin v1.0.0

  4. Users install with:
       irm https://raw.githubusercontent.com/$Manifest/main/install.ps1 | iex
"@
